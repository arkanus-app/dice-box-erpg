import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const artworkDirectory = path.join(root, 'scripts', 'theme-artwork')
const themesDirectory = path.join(root, 'public', 'assets', 'dice-box', 'themes')

const artwork = {
	critical: {
		file: 'vampire-v5-critical.svg',
		scale: 0.26
	},
	'hunger-critical': {
		file: 'vampire-v5-hunger-critical.svg',
		scale: 0.26
	},
	'hunger-failure': {
		file: 'vampire-v5-hunger-failure.svg',
		scale: 0.38
	},
	success: {
		file: 'vampire-v5-success.svg',
		scale: 0.26
	}
}

const faceCenters = {
	1: [286.208, 504.32],
	6: [354.816, 618.496],
	7: [355.84, 732.672],
	8: [284.672, 967.168],
	9: [356.352, 504.32],
	10: [356.864, 848.384]
}

const themes = {
	'vampire-v5-normal': {
		outline: '#090b10',
		faces: {
			6: 'success',
			7: 'success',
			8: 'success',
			9: 'success',
			10: 'critical'
		}
	},
	'vampire-v5-hunger': {
		outline: '#1a0207',
		faces: {
			1: 'hunger-failure',
			6: 'success',
			7: 'success',
			8: 'success',
			9: 'success',
			10: 'hunger-critical'
		}
	}
}

const pathPattern = /<path\b[^>]*\/>/gu

const readGlyph = async ([id, definition]) => {
	const source = await readFile(path.join(artworkDirectory, definition.file), 'utf8')
	const paths = source.match(pathPattern)
	if(!paths?.length) throw new Error(`No SVG paths found in ${definition.file}.`)
	if(/<(?:script|foreignObject|image)\b/iu.test(source)) {
		throw new Error(`Unsafe SVG element found in ${definition.file}.`)
	}
	const normalizedPaths = [...new Set(paths.map(svgPath =>
		svgPath.replace(/\sfill="[^"]*"/u, ' fill="currentColor"')
	))]
	return [id, {
		...definition,
		paths: normalizedPaths.join('')
	}]
}

const loadedArtwork = Object.fromEntries(
	await Promise.all(Object.entries(artwork).map(readGlyph))
)

const renderUse = (face, glyphId, foreground, outline) => {
	const center = faceCenters[face]
	const glyph = loadedArtwork[glyphId]
	if(!center || !glyph) throw new Error(`Missing placement for face ${face} (${glyphId}).`)
	const offsetX = center[0] - (125 * glyph.scale)
	const offsetY = center[1] - (125 * glyph.scale)
	return [
		`<g data-face="${face}" data-glyph="${glyphId}" color="${foreground}"`,
		` stroke="${outline}" stroke-width="8" stroke-linejoin="round"`,
		` paint-order="stroke fill" transform="translate(${offsetX.toFixed(3)} ${offsetY.toFixed(3)}) scale(${glyph.scale})">`,
		`<use href="#v5-${glyphId}"/></g>`
	].join('')
}

const renderAtlas = (theme, variant) => {
	const foreground = variant === 'light' ? '#ffffff' : '#111827'
	const usedGlyphs = [...new Set(Object.values(theme.faces))]
	const definitions = usedGlyphs.map(id => {
		const glyph = loadedArtwork[id]
		return `<g id="v5-${id}" data-source="scripts/theme-artwork/${glyph.file}">${glyph.paths}</g>`
	}).join('\n')
	const faces = Object.entries(theme.faces)
		.map(([face, glyphId]) => renderUse(Number(face), glyphId, foreground, theme.outline))
		.join('\n')
	return [
		'<?xml version="1.0" encoding="UTF-8"?>',
		'<!-- Generated by scripts/generate-vampire-themes.mjs; layout erpg-default-v1. -->',
		'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">',
		'<defs>',
		definitions,
		'</defs>',
		faces,
		'</svg>',
		''
	].join('\n')
}

for(const [themeName, theme] of Object.entries(themes)) {
	const outputDirectory = path.join(themesDirectory, themeName)
	await mkdir(outputDirectory, { recursive: true })
	for(const variant of ['light', 'dark']) {
		await writeFile(
			path.join(outputDirectory, `faces-${variant}.svg`),
			renderAtlas(theme, variant),
			'utf8'
		)
	}
}

console.log('Generated Vampire V5 normal and Hunger face atlases.')
